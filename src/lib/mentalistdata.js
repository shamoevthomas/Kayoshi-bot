// « R » = vraie personne : humaine, adulte, dans le monde d'aujourd'hui, masculine sauf « femme ».
const REAL = 'reel humain adulte moderne ~heros';
export const CHARACTERS = RAW.map(([name, work, traits]) => {
  const attrs = {};
  let list = traits.split(/\s+/);
  if (list[0] === 'R') list = [...REAL.split(' '), ...(list.includes('femme') ? [] : ['homme']), ...list.slice(1)];
  for (const t of list) {
    if (t.startsWith('~')) attrs[t.slice(1)] = 0.5;
    else attrs[t] = 1;
  }
  return { name, work, attrs, img: IMAGES[name] ?? null };
});
